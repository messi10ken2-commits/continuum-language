// Destructive steps are confined to a newly created, randomly named local DB.
// Requires the PostgreSQL container created by dev-local.sh; never production.
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import net from 'node:net';
import pg from 'pg';

const root=fileURLToPath(new URL('../',import.meta.url));
const name='continuum_migration_'+crypto.randomUUID().replaceAll('-','');
const admin=new pg.Client({connectionString:'postgresql://continuum_dev@127.0.0.1:55432/continuum_dev'});
await admin.connect();
let app,db,created=false;
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const listener=net.createServer();
await new Promise(resolve=>listener.listen(0,'127.0.0.1',resolve));
const port=listener.address().port;
await new Promise(resolve=>listener.close(resolve));
async function stop(){
 if(!app||app.exitCode!==null||app.signalCode!==null)return;
 const exited=new Promise(resolve=>app.once('exit',resolve));
 app.kill('SIGTERM');await Promise.race([exited,sleep(3000)]);
 if(app.exitCode===null&&app.signalCode===null){app.kill('SIGKILL');await exited;}
}
async function start(){
 let output='';
 app=spawn(process.execPath,['server.mjs'],{cwd:root,env:{...process.env,NODE_ENV:'development',PORT:String(port),DATABASE_URL:`postgresql://continuum_dev@127.0.0.1:55432/${name}`},stdio:['ignore','pipe','pipe']});
 app.stdout.on('data',chunk=>{output+=chunk});app.stderr.on('data',chunk=>{output+=chunk});
 for(let attempt=0;attempt<100;attempt++){
  if(app.exitCode!==null||app.signalCode!==null)throw Error('Migration server failed: '+output);
  try{if((await fetch(`http://127.0.0.1:${port}/api/health`)).ok)return}catch{}
  await sleep(100);
 }
 throw Error('Migration server did not become ready');
}
async function request(path,method='GET',body,cookie){
 const response=await fetch(`http://127.0.0.1:${port}/api${path}`,{method,headers:{'Content-Type':'application/json',...(cookie?{cookie}:{})},...(body?{body:JSON.stringify(body)}:{})});
 assert.ok(response.ok,`${method} ${path}: ${response.status}`);
 return {data:await response.json(),cookie:response.headers.get('set-cookie')?.split(';')[0]};
}
try{
 await admin.query(`CREATE DATABASE "${name}"`);created=true;
 db=new pg.Client({connectionString:`postgresql://continuum_dev@127.0.0.1:55432/${name}`});await db.connect();
 await start();
 const learner=await request('/auth/register','POST',{name:'Migration learner',email:'migration-learner@example.test',password:'synthetic-migration-password',role:'learner',adult:true});
 const teacher=await request('/auth/register','POST',{name:'Migration teacher',email:'migration-teacher@example.test',password:'synthetic-migration-password',role:'teacher',adult:true});
 const saved=await request('/practice','POST',{lesson:'subjunctive',answers:[1,1,1,1,1]},learner.cookie);
 const share=await request('/share-code','POST',{language:'es'},learner.cookie);
 await request('/teacher/connect','POST',{code:share.data.code},teacher.cookie);
 const note=await request(`/teacher/learners/${learner.data.user.id}/notes`,'POST',{language:'es',focus:'Migration check',note:'Existing teacher note must survive.'},teacher.cookie);
 const assessment=await request('/assessments','POST',{},learner.cookie);
 const before=(await db.query('SELECT id,password_hash FROM users ORDER BY id')).rows;
 await stop();
 // Simulate the prior users schema while retaining authentic session and
 // learning records generated by the application's actual endpoints.
 await db.query('ALTER TABLE users DROP COLUMN base_language');
 await start();
 assert.deepEqual((await db.query('SELECT id,password_hash FROM users ORDER BY id')).rows,before);
 assert.equal((await request('/auth/me','GET',null,learner.cookie)).data.user.baseLanguage,'en');
 assert.equal((await request('/auth/me','GET',null,teacher.cookie)).data.user.role,'teacher');
 assert.equal((await request('/practice','GET',null,learner.cookie)).data.attempts[0].id,saved.data.attempt.id);
 assert.equal((await request(`/teacher/learners/${learner.data.user.id}/notes`,'GET',null,teacher.cookie)).data.notes[0].id,note.data.note.id);
 assert.equal((await request('/assessments','GET',null,learner.cookie)).data.active.id,assessment.data.session.id);
 await request('/preferences','PUT',{baseLanguage:'ja'},learner.cookie);
 await stop();await start();
 assert.equal((await request('/auth/me','GET',null,learner.cookie)).data.user.baseLanguage,'ja');
 assert.equal((await request('/practice','GET',null,learner.cookie)).data.attempts[0].id,saved.data.attempt.id);
 console.log('PASS: repeated migrations preserve existing users, password hashes, sessions, practice, teacher sharing/notes, active assessment and saved base language.');
}finally{
 await stop();await db?.end();
 if(created)await admin.query(`DROP DATABASE "${name}"`);
 await admin.end();
}
